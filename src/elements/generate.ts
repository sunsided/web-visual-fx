import type { Param } from '../lib/params/schema.js';
import { elements, type ElementDefinition, type ExtraProp } from './config.js';

/**
 * Renders the custom element wrappers, their entry point and declarations from `config.ts`.
 * Pure; `scripts/generate-elements.js` writes the files (formatted with Prettier), and
 * `generate.spec.ts` fails when the committed wrappers are out of date.
 */

const HEADER = 'Generated by `yarn elements:generate` from src/elements/config.ts. Do not edit.';

interface PropInfo {
	/** Property name on the element. */
	name: string;
	/** Prop of the wrapped component, when it differs from `name`. */
	source?: string;
	type: ExtraProp['type'];
	ts: string;
	description: string;
}

/**
 * Schema props whose names are taken by HTMLElement: an element property would shadow
 * `element.blur()` and the Web Animations `element.animate()`. `generate.spec.ts` checks every
 * property against the DOM interfaces.
 */
const RENAMED: Record<string, string> = { blur: 'blurRadius', animate: 'animated' };

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const pascal = (s: string) =>
	s.replace(/(^|-)([a-z])/g, (_, __, c: string) => c.toUpperCase()).replace(/-/g, '');

function schemaProp(key: string, p: Param): PropInfo {
	const description = p.description ? `${p.label}. ${p.description}` : p.label;
	const name = RENAMED[key] ?? key;
	const source = RENAMED[key] ? key : undefined;
	switch (p.kind) {
		case 'range':
			return { name, source, type: 'Number', ts: 'number', description };
		case 'toggle':
			return { name, source, type: 'Boolean', ts: 'boolean', description };
		case 'select':
			return {
				name,
				source,
				type: 'String',
				ts: p.options.map((o) => `'${o}'`).join(' | '),
				description
			};
		case 'color':
			return {
				name,
				source,
				type: 'String',
				ts: 'string',
				description: `${description} (#rrggbb)`
			};
	}
}

export function propsOf(el: ElementDefinition): PropInfo[] {
	const props = Object.entries(el.schema).map(([k, p]) => schemaProp(k, p));
	for (const [name, extra] of Object.entries(el.extras ?? {})) props.push({ name, ...extra });
	if (el.motion) {
		props.push({
			name: 'paused',
			type: 'Boolean',
			ts: 'boolean',
			description: 'Pauses the CSS animations (WCAG 2.2.2).'
		});
	}
	return props;
}

function wrapper(el: ElementDefinition): string {
	const props = propsOf(el);
	const component = pascal(el.component.split('/')[1]);
	const twoWay = Object.entries(el.extras ?? {}).filter(([, x]) => x.event);
	const isTwoWay = (name: string) => twoWay.some(([k]) => k === name);
	// Every declared prop by name, no rest: Svelte copies *all* host attributes into props, and a
	// rest spread would forward the host's id, class, style and aria-* to the inner element too.
	const ownProps = props.map((p) => {
		const extra = el.extras?.[p.name];
		if (isTwoWay(p.name)) return `${p.name} = $bindable(${extra?.default ?? ''})`;
		if (p.name === 'paused' && el.motion) return 'paused = false';
		return extra?.default ? `${p.name} = ${extra.default}` : p.name;
	});

	const propsOption = props
		.map((p) => {
			const attribute = kebab(p.name) === p.name ? '' : `, attribute: '${kebab(p.name)}'`;
			return `\t\t\t${p.name}: { type: '${p.type}'${attribute} }`;
		})
		.join(',\n');

	const attrs = props
		.filter((p) => !isTwoWay(p.name) && !(p.name === 'paused' && el.motion))
		.map((p) => (p.source ? `${p.source}={${p.name}}` : `{${p.name}}`));
	for (const [k, x] of twoWay) {
		attrs.push(
			`bind:${k}={() => ${k}, (value) => { ${k} = value; $host().dispatchEvent(new CustomEvent('${x.event}', { detail: value })); }}`
		);
	}
	for (const e of el.events ?? []) {
		attrs.push(
			`${e.from}={(detail) => $host().dispatchEvent(new CustomEvent('${e.name}', { detail }))}`
		);
	}

	const slots = el.slots ?? [];
	const named = slots.filter((s) => s !== 'children');
	const body = [
		...named.map((s) => `{#snippet ${s}()}<slot name="${s}" />{/snippet}`),
		...(slots.includes('children') ? ['<slot />'] : [])
	];
	let markup =
		body.length > 0
			? `<${component} ${attrs.join(' ')}>${body.join('')}</${component}>`
			: `<${component} ${attrs.join(' ')} />`;
	if (el.motion) {
		markup = `<div class="vfx-motion" data-motion={paused ? 'paused' : 'running'}>${markup}</div>`;
	}

	return `<!-- ${HEADER} -->
<svelte:options
	customElement={{
		tag: '${el.tag}',
		shadow: 'open',
		props: {
${propsOption}
		},
		extend: withSharedStyles
	}}
/>

<script lang="ts">
	import ${component} from '../../lib/fx/${el.component}.svelte';
	import { withSharedStyles } from '../shadow.js';

	let { ${ownProps.join(', ')} } = $props();
</script>

${markup}

<style>
	:host {
		display: ${el.display ?? 'block'};
	}
</style>
`;
}

function entries(): string {
	// Re-exports rather than bare imports: bundlers may drop a bare import of a module they
	// consider side-effect free, and with it the element's registration.
	return `// ${HEADER}
// Importing this module registers every element.
${elements.map((el) => `export { default as Vfx${pascal(el.name)} } from './${el.name}.svelte';`).join('\n')}
`;
}

function doc(text: string, indent: string): string {
	return `${indent}/** ${text.replace(/\*\//g, '*\\/')} */\n`;
}

function declarations(): string {
	const imports = new Map<string, Set<string>>();
	for (const el of elements) {
		for (const [name, module] of Object.entries(el.types ?? {})) {
			if (!imports.has(module)) imports.set(module, new Set());
			imports.get(module)!.add(name);
		}
	}
	const importLines = [...imports].map(
		// Relative to dist/elements/, where the declarations are written.
		([module, names]) => `import type { ${[...names].join(', ')} } from '../${module}';`
	);

	const blocks = elements.map((el) => {
		const id = `Vfx${pascal(el.name)}`;
		const fields = propsOf(el)
			.map((p) => `${doc(p.description, '\t')}\t${p.name}?: ${p.ts};`)
			.join('\n');
		const events = [
			...(el.events ?? []).map((e) => ({
				name: e.name,
				detail: e.detail,
				description: e.description
			})),
			...Object.entries(el.extras ?? {})
				.filter(([, x]) => x.event)
				.map(([k, x]) => ({ name: x.event!, detail: x.ts, description: `\`${k}\` changed.` }))
		];
		const eventMap = events.length
			? `\nexport interface ${id}EventMap extends HTMLElementEventMap {\n${events
					.map((e) => `${doc(e.description, '\t')}\t${e.name}: CustomEvent<${e.detail}>;`)
					.join('\n')}\n}\n`
			: '';
		return `${doc(`Properties of \`<${el.tag}>\`. ${el.description}`, '')}export interface ${id}Props {\n${fields}\n}
${eventMap}
${doc(`\`<${el.tag}>\`: ${el.description}`, '')}export interface ${id}Element extends HTMLElement, ${id}Props {}

${doc(`Svelte component behind \`<${el.tag}>\`; \`.element\` is its custom element class.`, '')}export declare const ${id}: { readonly element?: CustomElementConstructor };`;
	});

	return `// ${HEADER}
${importLines.join('\n')}

${blocks.join('\n\n')}

declare global {
	interface HTMLElementTagNameMap {
${elements.map((el) => `\t\t'${el.tag}': Vfx${pascal(el.name)}Element;`).join('\n')}
	}
}
`;
}

function reactDeclarations(): string {
	const names = elements.map((el) => `Vfx${pascal(el.name)}`);
	const typeImports = elements.flatMap((el) => {
		const id = `Vfx${pascal(el.name)}`;
		return el.events?.length || Object.values(el.extras ?? {}).some((x) => x.event)
			? [`${id}Element`, `${id}Props`, `${id}EventMap`]
			: [`${id}Element`, `${id}Props`];
	});
	const intrinsic = elements.map((el, i) => {
		const id = names[i];
		const events = [
			...(el.events ?? []).map((e) => e.name),
			...Object.values(el.extras ?? {})
				.filter((x) => x.event)
				.map((x) => x.event!)
		];
		const handlers = events.length
			? ` & {\n${events.map((e) => `\t\t\t\ton${e}?: (event: ${id}EventMap['${e}']) => void;`).join('\n')}\n\t\t\t}`
			: '';
		return `\t\t\t'${el.tag}': ElementProps<${id}Element, ${id}Props>${handlers};`;
	});

	return `// ${HEADER}
// JSX types for React 19, which passes props to custom elements as properties and \`on<event>\`
// props as event listeners. Reference it once: \`import type {} from '@sunsided/web-visual-fx/elements/react';\`
import type { DetailedHTMLProps, HTMLAttributes } from 'react';
import type {
	${typeImports.join(',\n\t')}
} from './index.js';

type ElementProps<E extends HTMLElement, P> = Partial<P> &
	DetailedHTMLProps<HTMLAttributes<E>, E> & { class?: string };

declare module 'react' {
	namespace JSX {
		interface IntrinsicElements {
${intrinsic.join('\n')}
		}
	}
}
`;
}

/** Wrappers and entry, committed below `src/elements/generated/`; file name → contents. */
export function renderSources(): Map<string, string> {
	const files = new Map<string, string>();
	for (const el of elements) files.set(`${el.name}.svelte`, wrapper(el));
	files.set('index.ts', entries());
	return files;
}

/** Declarations, written next to the built elements in `dist/elements/` at package time. */
export function renderDeclarations(): Map<string, string> {
	const files = new Map<string, string>();
	files.set('index.d.ts', declarations());
	for (const el of elements) files.set(`${el.name}.d.ts`, `import './index.js';\n`);
	files.set('react.d.ts', reactDeclarations());
	return files;
}
